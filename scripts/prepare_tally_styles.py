def silver():
    """Keep the installed native shell strips and the existing dark body."""
    image = Image.new("RGBA", (CONTENT_WIDTH, CANVAS[1]))
    inset = 300 * 12 / 1024
    wall_width = 300 * 7 / 1024
    h, bevel = 27, 3.5
    ImageDraw.Draw(image).rectangle(
        (round(inset * SCALE), 0, round((300 - inset) * SCALE) - 1, round(h * SCALE) - 1),
        fill=(11, 12, 13, 245))
    wall = original.SHELL.crop((0, 35, 7, 92))
    original.paste(image, wall, inset, 0, wall_width, h - bevel)
    original.paste(image, wall.transpose(Image.Transpose.FLIP_LEFT_RIGHT),
                   300 - inset - wall_width, 0, wall_width, h - bevel)
    bottom = original.SHELL.crop((16, 105, 512, 112))
    original.paste(image, bottom, inset, h - bevel, 150 - inset, bevel)
    original.paste(image, bottom.transpose(Image.Transpose.FLIP_LEFT_RIGHT),
                   150, h - bevel, 150 - inset, bevel)
    return image


def graphite():
    """Use the selected Soft graphite contour; runtime owns counter dividers."""
    image = Image.new("RGBA", (CONTENT_WIDTH, CANVAS[1]))
    native_line = original.line

    def outer_line(canvas, points, color, width=1):
        # chamber() adds two plain vertical counter dividers. Keep those out
        # of the bitmap so the shared live counter renderer remains their owner.
        if (len(points) == 2 and points[0][0] == points[1][0]
                and abs(points[1][1] - points[0][1] - 19) < 0.001):
            return
        native_line(canvas, points, color, width)

    original.line = outer_line
    try:
        inset = 300 * 12 / 1024
        original.chamber(image, inset, -1, 300 - 2 * inset, 27, "round", "#a3aebc")
    finally:
        original.line = native_line
    return image


def make_detached(identifier, image, frame, content_y):
    """Close a standalone frame with its own structural trim and source alpha."""
    canvas = Image.new("RGBA", CANVAS)
    if identifier == "gothic04":
        # Its original closed surround has a continuous middle join; reflecting
        # the attached flare would duplicate the side-wall extension across it.
        surround = Image.new("RGBA", (CONTENT_WIDTH, CANVAS[1]))
        source = gothic.grade(gothic.asset("R04", (0, 0, 256, 32)), .38, 1.25)
        gothic.slice3(surround, source, 0, 0, 300, 40, 27)
        alpha = surround.getchannel("A")
        mask = Image.new("L", CANVAS)
        draw = ImageDraw.Draw(mask)
        for column in range(surround.width):
            occupied = [row for row in range(40 * SCALE) if alpha.getpixel((column, row)) >= 96]
            if occupied:
                draw.line((column, occupied[0], column, occupied[-1]), fill=255)
        gothic.tiled(canvas, gothic.BODY, 0, 0, 300, 40)
        canvas.putalpha(ImageChops.multiply(canvas.getchannel("A"), mask))
        canvas.alpha_composite(surround)
        row_center, extent = 20, 40
        method = "Use the original complete R04 surround (0,0,256,32), with its own closed silhouette."
    else:
        center = round(content_y * SCALE)
        upper = frame.crop((0, center, CONTENT_WIDTH, frame.getbbox()[3]))
        upper = upper.transpose(Image.Transpose.FLIP_TOP_BOTTOM)
        lower = image.crop((0, center, CONTENT_WIDTH, image.getbbox()[3]))
        canvas.alpha_composite(upper, (0, 0))
        canvas.alpha_composite(lower, (0, upper.height))
        row_center, extent = upper.height / SCALE, (upper.height + lower.height) / SCALE
        method = "Reflect structural lower half above the counter center; retain the original lower half."
    texture = identifier + "_detached.tga"
    canvas.save(OUT / texture, compression=None)
    return {"texture": texture, "extent": extent, "contentY": row_center,
            "sourceCenter": content_y, "structuralBottom": frame.getbbox()[3] / SCALE,
            "method": method}


def make_style(style):
    identifier, label, selected, height = style
    detached_frame = None
    if identifier == "silver":
        image = silver()
        sources = [{"path": "media/tex/actionbars/HDActionBar.tga",
                    "crops": [[0, 35, 7, 92], [16, 105, 512, 112]],
                    "use": "Existing native sidewalls and lower bevel; right pieces mirrored."}]
    elif identifier == "graphite":
        image = graphite()
        sources = [{"path": "scripts/preview_tally_designs.py", "design": "02",
                    "use": "Original Soft graphite contour and fill, excluding baked counter dividers."}]
    else:
        design = next(item for item in gothic.DESIGNS if item[0] == selected)
        image = Image.new("RGBA", (CONTENT_WIDTH, CANVAS[1]))
        if selected == "07":
            # Include the source's open upper walls rather than projecting an
            # unrelated backing across the pointed ends. Keep its native alpha.
            source = gothic.grade(gothic.asset("R25", (3, 22, 253, 51)), .25, 1.25)
            gothic.slice3(image, source, 0, 0, 300, 37, 30)
        elif selected == "10":
            # Follow the existing curved metal shoulder, removing only the
            # rectangular top-bar material above it. Keep the lower curls intact.
            source = gothic.grade(gothic.asset("ARPG", ARPG_CORNICE_CROP), .45, 1.4)
            top = ARPG_SHOULDER + [(source.width - 1 - x, y) for x, y in reversed(ARPG_SHOULDER)]
            mask = Image.new("L", source.size)
            ImageDraw.Draw(mask).polygon(top + [(source.width - 1, source.height - 1),
                                                (0, source.height - 1)], fill=255)
            source.putalpha(ImageChops.multiply(source.getchannel("A"), mask))
            gothic.paste(image, source, 0, 0, 300, 40)
        elif selected == "13":
            # Keep the selected frame while fitting the runtime pendant inside
            # the default joined-XP clearance. The proposal gallery is unchanged.
            base = list(design)
            base[3] = "dragon"
            gothic.lower(image, tuple(base), 0, 0)
            detached_frame = image.copy()
            footer_height = 14
            footer_width = 62 * footer_height / 18
            gothic.paste(image, gothic.grade(gothic.asset("N1", (208, 100, 304, 128)), .42, 1.25),
                         150 - footer_width / 2, 26, footer_width, footer_height)
        else:
            gothic.lower(image, design, 0, 0)
        source_ids = [key for key in design[4] if selected not in ("07", "10") or key != "R06"]
        sources = [{"id": key, **gothic.ASSETS[key]} for key in source_ids]
        if selected not in ("07", "10"):
            sources.append({"id": "R06", "crop": [0, 32, 64, 44],
                            "use": "Existing stone shading clipped inside the actual ornament silhouette."})
    bounds = image.getbbox()
    extent = bounds[3] / SCALE if bounds else height
    canvas = Image.new("RGBA", CANVAS)
    canvas.alpha_composite(image, (0, 0))
    canvas.save(OUT / (identifier + ".tga"), compression=None)
    content_y, content_scale = CONTENT_LAYOUTS.get(identifier, (min(height / 2, 16), 1))
    detached = make_detached(identifier, image, detached_frame if detached_frame is not None else image, content_y)
    return {"id": identifier, "label": label, "texture": identifier + ".tga",
            "height": height, "extent": extent, "artHeight": 64,
            "contentY": content_y, "contentScale": content_scale,
            "detached": detached,
            "sources": sources, "selectedProposal": selected,
            "occupiedPixelBounds": bounds,
            "runtimeAdaptation": ({
                "crop": [3, 22, 253, 51], "x": 0, "y": 0, "width": 300, "height": 37,
                "sliceCap": 30, "projectedBacking": False,
                "reason": "Use native open upper walls and pointed alpha, without the nine-unit rectangular top apron.",
            } if selected == "07" else {
                "crop": list(ARPG_CORNICE_CROP), "x": 0, "y": 0, "width": 300, "height": 40,
                "leftShoulder": ARPG_SHOULDER, "mirrorShoulder": True,
                "projectedBacking": False,
                "reason": "Follow the curved metal shoulders, excluding the rectangular outer wings without clipping the lower curls.",
            } if selected == "10" else {
                "upperBackingInset": 300 * 12 / 1024,
                "upperBackingHeight": 18,
                "reason": "Keep the backing inside the action bar's visible bottom edge above the native lower flare.",
            } if selected == "04" else {
                "centerRail": {"crop": [106, 88, 400, 106], "x": 29, "y": 23, "width": 242, "height": 14,
                               "reason": "Exclude the source edge fade so the original right cap joins without a gap."},
                "footerCrop": [208, 100, 304, 128],
                "centerX": 150, "y": 26, "width": 62 * 14 / 18,
                "height": 14, "reason": "Fit the default joined-XP lower clearance.",
            } if selected == "13" else None)}, image


def number(value):
    return str(int(value)) if value == int(value) else str(value)


def write_registry(rows, path):
    metadata = [NOTICE, 'DFRL.tallyStyleDefault = "%s"\n' % DEFAULT_STYLE,
                'DFRL.tallyStyleCanvas = { width = 300, height = 64, right = 600 / 1024, bottom = 1 }\n',
                'DFRL.tallyStyles = {\n']
    for entry, _ in rows:
        metadata.append('    {\n'
                        '        id = "%s",\n'
                        '        label = "%s",\n'
                        '        texture = "%s",\n'
                        '        height = %s,\n'
                        '        extent = %s,\n'
                        '        artHeight = 64,\n'
                        '        contentY = %s,\n'
                        '        contentScale = %s,\n'
                        '        detached = {\n'
                        '            texture = "%s",\n'
                        '            extent = %s,\n'
                        '            contentY = %s,\n'
                        '        },\n'
                        '    },\n'
                        % (entry["id"], entry["label"], entry["texture"],
                           number(entry["height"]), number(entry["extent"]),
                           number(entry["contentY"]), number(entry["contentScale"]),
                           entry["detached"]["texture"], number(entry["detached"]["extent"]),
                           number(entry["detached"]["contentY"])))
    metadata.append('}\nDFRL.tallyStyleById = {}\nfor _, style in ipairs(DFRL.tallyStyles) do\n    DFRL.tallyStyleById[style.id] = style\nend\n')
    path.write_text("".join(metadata))


def render():
    OUT.mkdir(parents=True, exist_ok=True)
    rows = [make_style(style) for style in STYLES]
    write_registry(rows, ROOT / "core/tally.lua")
    RECORDS.write_text(json.dumps({
        "preparation": "scripts/prepare_tally_styles.py", "default": DEFAULT_STYLE,
        "canvas": list(CANVAS), "contentPixels": [600, 128], "pixelScale": SCALE,
        "texCoord": [0, 600 / 1024, 0, 1], "styles": [entry for entry, _ in rows],
        "cropOverrides": json.loads((gothic.OUT / "sources.json").read_text())["cropOverrides"],
        "scope": "Attached open-top and detached enclosed compartment artwork; no icons, text or action bar.",
        "userSelectedRuntimeStyles": True,
    }, indent=2) + "\n")
    sheet = Image.new("RGB", (1440, ((len(rows) + 1) // 2) * 150), (24, 28, 34))
    draw = ImageDraw.Draw(sheet)
    font = ImageFont.truetype("/System/Library/Fonts/Supplemental/Arial.ttf", 17)
    for index, (entry, image) in enumerate(rows):
        x, y = (index % 2) * 720 + 20, (index // 2) * 150 + 12
        draw.text((x, y), entry["id"] + "  " + entry["label"], font=font, fill=(231, 224, 207))
        for yy in range(y + 28, y + 141, 16):
            for xx in range(x, x + 680, 16):
                draw.rectangle((xx, yy, xx + 15, yy + 15),
                               fill=(43, 46, 52) if (xx // 16 + yy // 16) % 2 else (58, 61, 68))
        sheet.paste(image, (x + 35, y + 30), image)
    sheet.save(PREVIEW)
    print("Prepared " + str(len(rows)) + " tally textures and core/tally.lua")
    print(PREVIEW)
    for entry, _ in rows:
        print(entry["id"], "height=" + number(entry["height"]), "extent=" + number(entry["extent"]))


if __name__ == "__main__":
    render()
