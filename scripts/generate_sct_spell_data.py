"""Prepare SCT area metadata from native ability records, without executing Lua.

The recovered RE catalog establishes the record layout and cast kinds. Classification
uses native cast kinds and radius, never a spell-name/ID allowlist or hit count.
"""

import argparse
import hashlib
import math
from pathlib import Path
import re
import struct

from generate_spell_icons import lua_string
from native_pe import PeImage


SOURCE_SHA256 = "eb5fd1c1b96e6180fcf5f3d685d90a61471af28d22e5f060c02b7b7663fbf79e"
STRIDE = 120


def native_rows(raw, reference):
    section = reference.split("pub static ABILITIES:", 1)[1].split("pub static CLASSES:", 1)[0]
    keys = re.findall(r'\bkey:\s*"([a-z][a-z0-9_]*)"', section)
    if not keys or len(keys) != len(set(keys)):
        raise ValueError("Expected the complete ordered recovered ability catalog")
    image = PeImage(raw)

    def string(at):
        address, length = struct.unpack_from("<QQ", raw, at)
        if not 0 < length <= 256:
            raise ValueError("Invalid native ability string")
        return image.read(address, length).decode("utf-8")

    def row(at):
        key, name, icon = string(at), string(at + 16), string(at + 32)
        if not re.fullmatch(r"[a-z][a-z0-9_]*", key) or not re.fullmatch(r"[A-Za-z0-9_]+", icon):
            raise ValueError("Unexpected native ability identity")
        address, count = struct.unpack_from("<QQ", raw, at + 48)
        if not 0 < count <= 5 or any(value > 4 for value in image.read(address, count)):
            raise ValueError("Unexpected native upgrade kinds")
        kind, school = raw[at + 117], raw[at + 116]
        radius = struct.unpack_from("<f", raw, at + 80)[0]
        if kind > 11 or school > 6 or not math.isfinite(radius) or radius < 0:
            raise ValueError("Unexpected native cast metadata")
        return {
            "key": key,
            "name": name,
            "spell": struct.unpack_from("<I", raw, at + 64)[0],
            "pulse": struct.unpack_from("<I", raw, at + 100)[0],
            "kind": kind,
            "radius": radius,
        }

    # This exact table was located by its UTF-8 fat-pointer identities in the
    # pinned newer executable. Include every current row, including additions
    # and removals relative to the historical RE source; do not reuse old data.
    start, count = 0x711B6A8, 114
    rows = [row(start + index * STRIDE) for index in range(count)]
    current = [value["key"] for value in rows]
    if len(current) != len(set(current)):
        raise ValueError("Repeated native ability key")
    common = set(current) & set(keys)
    if [key for key in current if key in common] != [key for key in keys if key in common]:
        raise ValueError("Native ability ordering disagrees with the recovered catalog")
    try:
        following = row(start + count * STRIDE)
    except (ValueError, struct.error, UnicodeError, IndexError):
        following = None
    if following is not None:
        raise ValueError("Native ability table extends beyond the pinned record count")
    return start, rows



def area(row):
    # Recovered dispatch: radial, ground-periodic and cone casts. A totem or
    # class-special uses its area path only with a positive definition radius.
    # A chain's hop radius and multiple separately selected targets are not AoE.
    return row["kind"] in (2, 3, 8) or (row["kind"] in (10, 11) and row["radius"] > 0)


def prepare(raw, reference):
    fingerprint = hashlib.sha256(raw).hexdigest()
    if fingerprint != SOURCE_SHA256:
        raise ValueError("Unreviewed native executable SHA256: " + fingerprint)
    offset, rows = native_rows(raw, reference)
    by_id, by_name = {}, {}
    for value in rows:
        classified = area(value)
        by_name.setdefault(value["name"], set()).add(classified)
        for spell in (value["spell"], value["pulse"]):
            if spell:
                by_id.setdefault(spell, {}).setdefault(value["name"], set()).add(classified)

    def boolean(values):
        if len(values) != 1:
            raise ValueError("Conflicting same-name native area classification")
        return "true" if next(iter(values)) else "false"

    lines = [
        "-- Generated by scripts/generate_sct_spell_data.py; do not edit by hand.",
        "-- Native cast geometry only; no current-target, timing or ownership inference.",
        "-- Executable SHA256: " + fingerprint,
        "-- Recovered catalog SHA256: " + hashlib.sha256(reference.encode()).hexdigest(),
        "-- Native table file offset: " + hex(offset) + "; records: " + str(len(rows)) + "; stride: 120",
        "-- Radial/ground/cone casts and positive-radius totem/class-special pulses are area damage.",
        "-- Chain hops and separately selected projectiles/melee/DoTs retain their own categories.",
        "DFRL.tools.SctSpellData = {",
        "    byId = {",
    ]
    for spell, names in sorted(by_id.items()):
        values = set.union(*names.values())
        if len(values) == 1:
            lines.append("        [" + str(spell) + "] = " + boolean(values) + ",")
        else:
            lines.append("        [" + str(spell) + "] = {")
            for name, choices in sorted(names.items()):
                lines.append("            [" + lua_string(name) + "] = " + boolean(choices) + ",")
            lines.append("        },")
    lines.extend(["    },", "    byName = {"])
    for name, values in sorted(by_name.items()):
        lines.append("        [" + lua_string(name) + "] = " + boolean(values) + ",")
    lines.extend(["    },", "}", ""])
    return "\n".join(lines), len(rows), sum(area(value) for value in rows)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--exe", type=Path, required=True)
    parser.add_argument("--reference-catalog", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=Path("modules/nameplates/spell_data.lua"))
    args = parser.parse_args()
    source, count, areas = prepare(args.exe.read_bytes(), args.reference_catalog.read_text())
    args.output.write_text(source)
    print("Prepared " + str(count) + " native ability records; " + str(areas) + " area classifications")
