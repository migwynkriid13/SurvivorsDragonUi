#!/usr/bin/env python3
"""Author native icon metadata from extracted DBCs and a native game catalog JSON.

This reads data only. It never imports, loads or executes addon or game code.
The JSON input has a source object and records with exact name/icon strings.
"""

from pathlib import Path
import argparse
import hashlib
import json
import re
import struct


LOCALES = ("enUS", "koKR", "frFR", "deDE", "zhCN", "zhTW", "esES", "esMX")
SCHOOLS = ("Physical", "Holy", "Fire", "Nature", "Frost", "Shadow", "Arcane")
QUESTION_MARK = "interface\\icons\\inv_misc_questionmark"


class Dbc:
    """The fixed-width unsigned records and UTF-8 string block of a WDBC file."""

    def __init__(self, path, fields):
        self.path = Path(path)
        self.data = self.path.read_bytes()
        if len(self.data) < 20:
            raise ValueError("Truncated DBC header: " + str(self.path))
        magic, count, actual_fields, size, strings_size = struct.unpack_from(
            "<4s4I", self.data
        )
        if magic != b"WDBC" or actual_fields != fields or size != fields * 4:
            raise ValueError("Unexpected DBC record layout: " + str(self.path))
        self.count = count
        self.fields = fields
        self.strings_start = 20 + count * size
        self.strings_size = strings_size
        if self.strings_start + strings_size != len(self.data):
            raise ValueError("Truncated or extended DBC payload: " + str(self.path))

    def records(self):
        return struct.iter_unpack(
            "<" + "I" * self.fields,
            memoryview(self.data)[20 : self.strings_start],
        )

    def string(self, offset):
        if not 0 <= offset < self.strings_size:
            raise ValueError("DBC string offset out of bounds: " + str(self.path))
        start = self.strings_start + offset
        end = self.data.find(b"\0", start)
        if end == -1:
            raise ValueError("Unterminated DBC string: " + str(self.path))
        return self.data[start:end].decode("utf-8")

    def sha256(self):
        return hashlib.sha256(self.data).hexdigest()


def native_icon(value):
    """Preserve native paths while comparing case/slash/extension variants once."""
    if not isinstance(value, str) or not value:
        return None
    path = value.replace("/", "\\")
    key = path.lower()
    if key.endswith((".blp", ".tga")):
        key = key[:-4]
    if key == QUESTION_MARK:
        return None
    return key, path


def add_icon(groups, name, icon):
    if not isinstance(name, str) or not name:
        return
    native = native_icon(icon)
    if native is None:
        return
    key, path = native
    choices = groups.setdefault(name, {})
    choices[key] = min(choices.get(key, path), path)


def resolve_groups(groups):
    return {
        name: next(iter(choices.values())) if len(choices) == 1 else False
        for name, choices in groups.items()
    }


def lua_string(value):
    """Quote UTF-8 text using escapes supported by the client's Lua 5.0."""
    quote = "'" if '"' in value and "'" not in value else '"'
    escaped = []
    for character in value:
        if character in (quote, "\\"):
            escaped.append("\\" + character)
        elif ord(character) < 32 or ord(character) == 127:
            escaped.append("\\" + format(ord(character), "03d"))
        else:
            escaped.append(character)
    return quote + "".join(escaped) + quote


def write_catalog(output, game, locales, schools, provenance, abilities=None):
    abilities = abilities or {}
    catalogs = [game, abilities] + list(locales.values())
    base_paths = {icon for catalog in catalogs for icon in catalog.values() if icon}
    school_paths = {
        icon for by_school in schools.values() for catalog in by_school.values() for icon in catalog.values() if icon
    }
    # Preserve existing base indices; append only the new refinement artwork.
    paths = sorted(base_paths) + sorted(school_paths - base_paths)
    indices = {path: index for index, path in enumerate(paths, 1)}
    lines = [
        "-- Generated by scripts/generate_spell_icons.py; do not edit by hand.",
        "-- Native display metadata only: no spell ownership, timing or gameplay state.",
        "-- Exact names only; conflicting native icons remain false, never guessed.",
        "-- School refinements narrow DBC name ambiguities using native School column 1.",
    ]
    for label, value in provenance:
        lines.append("-- " + label + ": " + str(value))
    lines += ["", "local icons = {"]
    lines += ["    " + lua_string(path) + "," for path in paths]
    lines += ["}", "", "DFRL.tools.SpellIconCatalog = {"]

    def append_names(catalog, indent):
        for name in sorted(catalog):
            value = catalog[name]
            expression = "icons[" + str(indices[value]) + "]" if value else "false"
            lines.append(indent + "[" + lua_string(name) + "] = " + expression + ",")

    lines.append("    game = {")
    append_names(game, "        ")
    lines += ["    },", "    abilities = {"]
    append_names(abilities, "        ")
    lines += ["    },", "    locales = {"]
    for locale, catalog in locales.items():
        if catalog:
            lines.append("        " + locale + " = {")
            append_names(catalog, "            ")
            lines.append("        },")
        else:
            lines.append("        " + locale + " = {},")
    lines += ["    },", "    schools = {"]
    for locale, by_school in schools.items():
        if by_school:
            lines.append("        " + locale + " = {")
            for school, catalog in by_school.items():
                lines.append("            " + school + " = {")
                append_names(catalog, "                ")
                lines.append("            },")
            lines.append("        },")
        else:
            lines.append("        " + locale + " = {},")
    lines += ["    },", "}", ""]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")
    return len(paths)


def catalog_counts(catalog):
    resolved = sum(isinstance(value, str) for value in catalog.values())
    return {"names": len(catalog), "resolved": resolved, "ambiguous": len(catalog) - resolved}


def refresh_game_catalog(output, game, abilities, provenance):
    """Replace native game data, preserving the already generated DBC tiers.

    Read only the generated path pool's JSON-compatible string literals. No Lua
    is loaded or evaluated, and existing DBC tables and indices stay untouched.
    """
    source = output.read_text(encoding="utf-8")
    pool = re.search(r"^local icons = \{\n(.*?)^\}", source, re.MULTILINE | re.DOTALL)
    if not pool:
        raise ValueError("Missing generated icon path pool")
    paths = [json.loads(line.strip().removesuffix(",")) for line in pool[1].splitlines()]
    indices = {path: index for index, path in enumerate(paths, 1)}
    native_paths = {value for catalog in (game, abilities) for value in catalog.values() if value}
    for path in sorted(native_paths - set(paths)):
        paths.append(path)
        indices[path] = len(paths)
    pool_source = "".join("    " + lua_string(path) + ",\n" for path in paths)
    source = source[:pool.start(1)] + pool_source + source[pool.end(1):]
    for label, catalog in (("game", game), ("abilities", abilities)):
        lines = ["    " + label + " = {"]
        for name in sorted(catalog):
            value = catalog[name]
            expression = "icons[" + str(indices[value]) + "]" if value else "false"
            lines.append("        [" + lua_string(name) + "] = " + expression + ",")
        lines.append("    },")
        replacement = "\n".join(lines)
        block = re.search(r"^    " + label + r" = \{\n.*?^    \},", source, re.MULTILINE | re.DOTALL)
        if block:
            source = source[:block.start()] + replacement + source[block.end():]
        elif label == "abilities" and "    locales = {" in source:
            source = source.replace("    locales = {", replacement + "\n    locales = {", 1)
        else:
            raise ValueError("Missing generated native game table: " + label)
    for label, value in provenance:
        pattern = r"^-- " + re.escape(label) + r": .*?$"
        source, count = re.subn(pattern, lambda _: "-- " + label + ": " + str(value), source, flags=re.MULTILINE)
        if count != 1:
            raise ValueError("Missing or repeated provenance field: " + label)
    output.write_text(source, encoding="utf-8")
    return len(paths)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spell-dbc", type=Path)
    parser.add_argument("--spell-icon-dbc", type=Path)
    parser.add_argument("--game-catalog", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--refresh-game-only", action="store_true", help="Keep the output's existing generated DBC data")
    arguments = parser.parse_args()
    game_bytes = arguments.game_catalog.read_bytes()
    metadata = json.loads(game_bytes)
    game_groups, ability_groups = {}, {}
    for record in metadata["records"]:
        groups = ability_groups if record.get("kind") == "ability" else game_groups
        add_icon(groups, record["name"], record["icon"])
    game = resolve_groups(game_groups)
    abilities = resolve_groups(ability_groups)
    game_provenance = [("Native game catalog JSON SHA256", hashlib.sha256(game_bytes).hexdigest())]
    if metadata.get("source", {}).get("sha256"):
        game_provenance.append(("Native game executable SHA256", metadata["source"]["sha256"]))
    if arguments.refresh_game_only:
        if arguments.spell_dbc or arguments.spell_icon_dbc:
            parser.error("--refresh-game-only retains existing DBC data; omit DBC input paths")
        path_count = refresh_game_catalog(arguments.output, game, abilities, game_provenance)
        print(
            json.dumps(
                {
                    "native_game_records": len(metadata["records"]),
                    "game": catalog_counts(game),
                    "abilities": catalog_counts(abilities),
                    "unique_icon_paths": path_count,
                    "output": str(arguments.output),
                },
                indent=2,
            )
        )
        return
    if not arguments.spell_dbc or not arguments.spell_icon_dbc:
        parser.error("Full generation needs --spell-dbc and --spell-icon-dbc")
    spells = Dbc(arguments.spell_dbc, 173)
    spell_icons = Dbc(arguments.spell_icon_dbc, 2)
    icon_paths = {record[0]: spell_icons.string(record[1]) for record in spell_icons.records()}
    locale_groups = {locale: {} for locale in LOCALES}
    school_groups = {locale: {school: {} for school in SCHOOLS} for locale in LOCALES}
    for record in spells.records():
        icon = icon_paths.get(record[117])
        school = SCHOOLS[record[1]] if record[1] < len(SCHOOLS) else None
        for column, locale in enumerate(LOCALES, 120):
            name = spells.string(record[column])
            add_icon(locale_groups[locale], name, icon)
            if school is not None:
                add_icon(school_groups[locale][school], name, icon)
    locales = {locale: resolve_groups(groups) for locale, groups in locale_groups.items()}
    schools = {locale: {} for locale in LOCALES}
    for locale, by_school in school_groups.items():
        for school, groups in by_school.items():
            # Emit only refinements of an existing name-wide DBC ambiguity.
            # Every matching row contributes; differing icons within a school
            # remain false rather than selecting a convenient spell record.
            ambiguous = {name: choices for name, choices in groups.items() if locales[locale].get(name) is False}
            if ambiguous:
                schools[locale][school] = resolve_groups(ambiguous)

    provenance = [
        ("Spell.dbc SHA256", spells.sha256()),
        ("SpellIcon.dbc SHA256", spell_icons.sha256()),
    ] + game_provenance
    path_count = write_catalog(arguments.output, game, locales, schools, provenance, abilities)
    school_counts = [catalog_counts(catalog) for by_school in schools.values() for catalog in by_school.values()]
    print(
        json.dumps(
            {
                "output": str(arguments.output),
                "bytes": arguments.output.stat().st_size,
                "unique_icon_paths": path_count,
                "spell_records": spells.count,
                "native_game_records": len(metadata["records"]),
                "game": catalog_counts(game),
                "abilities": catalog_counts(abilities),
                "locales": {locale: catalog_counts(catalog) for locale, catalog in locales.items()},
                "school_refinements": {
                    "entries": sum(count["names"] for count in school_counts),
                    "resolved": sum(count["resolved"] for count in school_counts),
                    "ambiguous": sum(count["ambiguous"] for count in school_counts),
                    "locales": {
                        locale: {school: catalog_counts(catalog) for school, catalog in by_school.items()}
                        for locale, by_school in schools.items()
                    },
                },
            },
            ensure_ascii=False,
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
